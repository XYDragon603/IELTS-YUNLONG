import { readdir, stat, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { bookNumber, audioIdentity, resourceURL } from '../lib/resource-parser.js';

const root = fileURLToPath(new URL('../', import.meta.url));
async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  return (await Promise.all(entries.map(e => e.isDirectory() ? walk(path.join(dir,e.name)) : path.join(dir,e.name)))).flat();
}
const files = (await walk(path.join(root, 'IELTS'))).map(f=>path.relative(root,f).replaceAll('\\','/')).sort();
const books = Array.from({length:17},(_,i)=>({number:i+4,documents:[],explanations:[],videos:[],tests:Array.from({length:4},(_,j)=>({number:j+1,audio:{}}))}));
const ignored = [], counts = {};
for (const file of files) {
  const ext = path.extname(file).toLowerCase();counts[ext]=(counts[ext]||0)+1;
  if (ext === '.mp3') {
    const identity = audioIdentity(file);
    if (!identity || (await stat(path.join(root,file))).size === 0) { ignored.push(file); continue; }
    const test=books.find(b=>b.number===identity.book)?.tests[identity.test-1];
    if(test&&!test.audio[identity.part]) test.audio[identity.part]={path:file,url:resourceURL(file),originalTest:identity.originalTest};
  } else if (ext === '.pdf') {
    if (/\(1\)|（G类）|样题/.test(file)) continue;
    const name=file.split('/').at(-1);
    const combined=/456/.test(name);
    const number=bookNumber(name);
    const targets=combined?books.filter(b=>[4,5,6].includes(b.number)):books.filter(b=>b.number===number);
    const explanation=/精讲/.test(name);
    for (const book of targets) {
      const list=explanation?book.explanations:book.documents;
      if(!list.some(d=>d.name===name))list.push({name,path:file,url:resourceURL(file),test:Number(name.match(/Test\s*(\d)/i)?.[1])||null});
    }
  } else if (ext === '.mp4') {
    const match=file.match(/(听力|阅读)C(\d+)T(\d+)/);
    if(match)books.find(b=>b.number===Number(match[2]))?.videos.push({test:Number(match[3]),skill:match[1]==='听力'?'listening':'reading',path:file,url:resourceURL(file)});
  } else if(ext==='.downloading') ignored.push(file);
}
await mkdir(path.join(root,'resources'),{recursive:true});
await writeFile(path.join(root,'resources','manifest.js'),`// Generated by npm run scan:resources. Original files are read only.\nexport const manifest = ${JSON.stringify({scannedAt:new Date().toISOString(),counts,ignored,books},null,2)};\n`);
console.log(JSON.stringify({counts,unmappedOrIncomplete:ignored.length,books:books.map(b=>({book:b.number,pdf:b.documents.length,explanations:b.explanations.length,audio:b.tests.reduce((n,t)=>n+Object.keys(t.audio).length,0)}))},null,2));
